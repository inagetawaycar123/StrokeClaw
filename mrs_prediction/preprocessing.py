"""Fold-local preprocessing for structured clinical variables."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Mapping, Sequence

import numpy as np

from .schema import FEATURE_SCHEMA_VERSION, RAW_COLUMN_BY_FEATURE, feature_names_for_mode


def _number_or_nan(value: Any) -> float:
    if value is None:
        return float("nan")
    if isinstance(value, str):
        value = value.strip()
        if not value or value.lower() in {"nan", "na", "n/a", "none", "null", "sf"}:
            return float("nan")
    try:
        result = float(value)
    except (TypeError, ValueError):
        return float("nan")
    return result if np.isfinite(result) else float("nan")


def _sex_or_nan(value: Any) -> float:
    token = str(value or "").strip().lower()
    if token in {"m", "male", "1"}:
        return 1.0
    if token in {"f", "female", "0", "2"}:
        return 0.0
    return float("nan")


def extract_feature_values(record: Mapping[str, Any], model_mode: str) -> dict[str, float]:
    """Convert one manifest/clinical row to named numeric V0 features.

    The model receives onset-to-CT in hours. Patient manifests generated by V0.2
    contain the audited `onset_to_ct_hours` derivative. The source Excel value
    remains untouched. A raw-day fallback exists only for synthetic/legacy rows
    that do not yet contain the V0.2 derivative.
    """

    values: dict[str, float] = {}
    for name in feature_names_for_mode(model_mode):
        if name == "sex":
            values[name] = _sex_or_nan(record.get("Gender"))
        elif name == "onset_to_ct_time":
            derived_hours = _number_or_nan(record.get("onset_to_ct_hours"))
            if np.isfinite(derived_hours):
                values[name] = derived_hours
            else:
                raw_days = _number_or_nan(record.get("Onset to CT time"))
                values[name] = raw_days * 24.0 if np.isfinite(raw_days) and 0.0 <= raw_days < 1.0 else float("nan")
        elif name == "nihss_change_24h":
            baseline = _number_or_nan(record.get("NIHSS Baseline"))
            followup = _number_or_nan(record.get("NIHSS 24 HOURS"))
            values[name] = followup - baseline if np.isfinite(baseline) and np.isfinite(followup) else float("nan")
        else:
            raw_column = RAW_COLUMN_BY_FEATURE[name]
            values[name] = _number_or_nan(record.get(str(raw_column)))
    return values


@dataclass
class ClinicalPreprocessor:
    """Median-impute, standardize, and append missing indicators.

    `fit` must be called on the training patients of one fold only. Validation
    and test patients are transformed with the stored fold-local statistics.
    """

    model_mode: str = "baseline"
    eps: float = 1e-6
    feature_names: tuple[str, ...] = field(init=False)
    medians: dict[str, float] = field(default_factory=dict)
    means: dict[str, float] = field(default_factory=dict)
    stds: dict[str, float] = field(default_factory=dict)
    fitted: bool = False

    def __post_init__(self) -> None:
        self.feature_names = feature_names_for_mode(self.model_mode)

    @property
    def output_feature_names(self) -> tuple[str, ...]:
        return self.feature_names + tuple(f"{name}__missing" for name in self.feature_names)

    @property
    def output_dim(self) -> int:
        return len(self.output_feature_names)

    def fit(self, records: Sequence[Mapping[str, Any]]) -> "ClinicalPreprocessor":
        if not records:
            raise ValueError("ClinicalPreprocessor.fit requires at least one training record")
        matrix = np.asarray(
            [[extract_feature_values(record, self.model_mode)[name] for name in self.feature_names] for record in records],
            dtype=np.float64,
        )
        for index, name in enumerate(self.feature_names):
            observed = matrix[:, index][np.isfinite(matrix[:, index])]
            if observed.size == 0:
                raise ValueError(f"Training fold has no observed values for feature {name!r}")
            median = float(np.median(observed))
            mean = float(np.mean(observed))
            std = float(np.std(observed, ddof=0))
            self.medians[name] = median
            self.means[name] = mean
            self.stds[name] = std if std > self.eps else 1.0
        self.fitted = True
        return self

    def transform_one(self, record: Mapping[str, Any]) -> np.ndarray:
        if not self.fitted:
            raise RuntimeError("ClinicalPreprocessor must be fitted on the fold training set")
        raw = extract_feature_values(record, self.model_mode)
        scaled: list[float] = []
        missing: list[float] = []
        for name in self.feature_names:
            value = raw[name]
            is_missing = not np.isfinite(value)
            imputed = self.medians[name] if is_missing else value
            scaled.append((imputed - self.means[name]) / self.stds[name])
            missing.append(float(is_missing))
        return np.asarray(scaled + missing, dtype=np.float32)

    def transform(self, records: Sequence[Mapping[str, Any]]) -> np.ndarray:
        if not records:
            return np.empty((0, self.output_dim), dtype=np.float32)
        return np.stack([self.transform_one(record) for record in records])

    def to_dict(self) -> dict[str, Any]:
        if not self.fitted:
            raise RuntimeError("Cannot serialize an unfitted ClinicalPreprocessor")
        return {
            "feature_schema_version": FEATURE_SCHEMA_VERSION,
            "model_mode": self.model_mode,
            "feature_names": list(self.feature_names),
            "output_feature_names": list(self.output_feature_names),
            "medians": self.medians,
            "means": self.means,
            "stds": self.stds,
            "gender_mapping": {"F": 0.0, "M": 1.0},
            "onset_to_ct_transform": "audited_modulo_24h_source_times_in_hours",
            "missing_strategy": "training_fold_median_plus_missing_indicator",
        }

    @classmethod
    def from_dict(cls, payload: Mapping[str, Any]) -> "ClinicalPreprocessor":
        if payload.get("feature_schema_version") != FEATURE_SCHEMA_VERSION:
            raise ValueError("Clinical preprocessor feature schema version is incompatible")
        instance = cls(model_mode=str(payload["model_mode"]))
        if tuple(payload.get("feature_names", ())) != instance.feature_names:
            raise ValueError("Clinical preprocessor feature order is incompatible")
        instance.medians = {str(k): float(v) for k, v in dict(payload["medians"]).items()}
        instance.means = {str(k): float(v) for k, v in dict(payload["means"]).items()}
        instance.stds = {str(k): float(v) for k, v in dict(payload["stds"]).items()}
        instance.fitted = True
        return instance
